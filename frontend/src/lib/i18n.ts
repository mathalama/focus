const languageLocales: Record<AppLanguage, string> = {
  en: 'en-US',
  ru: 'ru-RU',
  kk: 'kk-KZ',
};

const interpolate = (template: string, params?: Params) => {
  if (!params) return template;
  return Object.entries(params).reduce((acc, [key, value]) => {
    return acc.split(`{{${key}}}`).join(String(value));
  }, template);
};

export const translate = (language: AppLanguage, key: string, params?: Params) => {
  const raw = translations[language][key] ?? translations.en[key] ?? key;
  return interpolate(raw, params);
};

export const getLocale = (language: AppLanguage) => languageLocales[language] ?? languageLocales.en;

export const useI18n = () => {
  const { language } = useLanguage();
  return useMemo(
    () => ({
      language,
      locale: getLocale(language),
      t: (key: string, params?: Params) => translate(language, key, params),
    }),
    [language],
  );
};
